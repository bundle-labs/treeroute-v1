"""split.yaml of a coral table package from the visit table: owner rulings V5 and V6 (package side, not engine).
The default package is coral_draft; --split names another (for example the 2017-2020 sensitivity copy).

    py -3.9 -u make_split.py [--visits D:/treeroute/coral_build/coral_data/visits.parquet] [--write | --check]
    py -3.9 -u make_split.py --lead-dir D:/treeroute/coral_build/coral_data/full --check     # after stage 2

Written 2026-10-19 for owner ruling V (OWNER_RULINGS_2026-10-06.md:107-108). Reads only --visits (stage 1 output of
build_visits.py). It is not a CODE_FILE of build_tables.py (build_tables.py:104), so it never forces a rebuild.

The sample is the lead-0 file's rows: present_L0 and mark != unused (build_visits.py:211). The rules, in order:
  O13 (V5): a group with 0 present train rows at ANY of the 6 bank cuts. The cuts are the census cuts
            (build_visits.py:204-210); a train row counts at a cut when target_date <= cut and present_L<lead>
            (build_visits.py:248-249). The engine's table option refuses such a group (fit/bank.py:200-206).
  O14 (V5): a group with one site (unit). derive_overlap_blocks refuses it (split.py:795-797).
  V6:       a group not left out by V5 with no test row in the lead files (at one lead or more). Under leave one
            region out a group with no test row cannot be scored (G-SPLIT; BUILD_NOTES_table.md:68-79). A group
            can hold test-window visits and still have no test row: a visit with no lead-0 SST history is not
            written (present_L0 False; Gulf of Thailand has 10 such visits).
  seen_during_design: every other group (legacy donor or test ecoregion; split.yaml header).

--check (the default) recomputes and compares with the --split file: exit 0 when the excluded set and the
seen_during_design set are equal, exit 1 otherwise. --write rewrites coral_draft/split.yaml (the old file moves to
D:/treeroute/coral_build/_moved/v_split_<stamp>/ first; nothing is deleted). Writes only under D:/treeroute/coral_build.
The package name and the decision-surface years in the text come from --split and the test years (review fix,
2026-10-19), so the same script serves the 2017-2020 sensitivity row.
After the full stage-2 build, rerun --check with --lead-dir <full build folder>: stage 2 may drop rows by the MMM rule
(SPEC_CORAL_TABLES.md 1.4), and a group could then change list. --lead-dir reads only the key columns of
lead_<L>.parquet; a row is present at lead L when its row_id is in that file.
"""
import argparse
import datetime as dt
import os
import shutil
import sys
import time

import numpy as np
import pandas as pd
import yaml

BUILD_ROOT = r"D:\treeroute\coral_build"
DRAFT_SPLIT = os.path.join(BUILD_ROOT, "engine", "datasets", "coral_draft", "split.yaml")
LEADS = (0, 183, 365)
INNER_SCORE_YEARS = 3          # build_visits.py INNER_SCORE_YEARS (decision-surface years: y0-3 to y0-1)
SIGNED = "2026-10-19"

HEADER = """\
# split.yaml -- %(pkg)s (SPEC_TABLE_MODE.md 1.4; schema treeroute/package/schema.py:477-490). GENERATED by
# coral_tables/make_split.py --write (%(stamp)s) from %(src)s.
# Leave one ecoregion out (rulings D, E, H1): no donor or test list; every group in the lead files that is not
# excluded trains its own trees and is tested on its test rows (test window %(ty0)d-%(ty1)d).
# excluded, signed by owner ruling V (OWNER_RULINGS_2026-10-06.md:107-108, 2026-10-19), disclosed in exceptions.yaml
# (G-SPLIT) and ingest/README.md:
#   V5: the %(n5)d groups the engine defaults refuse (SPEC_TABLE_MODE.md 7 O13: 0 train rows at a bank cut; O14: one
#       site). Rows lost: %(t5)s test, %(r5)s train.
#   V6: the %(n6)d groups with no test row in the lead files after V5. Rows lost: %(r6)s train visits (%(s6)s sites);
#       %(d6)s of them are %(dy0)d-%(dy1)d decision-surface rows. These rows also leave every neighbour pool and every bank: the
#       engine drops excluded rows after the contract checks (package/table.py:505-507).
#   Their rows stay in the lead files, so no rebuild is needed.
# After both: %(nk)d groups, %(rk)s train and %(tk)s test visits at lead 0 (%(dk)s decision-surface rows).
# seen_during_design: every kept group. Each was a donor or a test ecoregion of the legacy runs (fullscale_split.json:
# 20 donors, every other ecoregion with feature rows tested; forecast_features_L0.parquet ecoregion set), and the
# legacy runs scored the 2016-2019 rows of 24 ecoregions (APP_PLAN.md:310).
"""


def cuts_of(test_years):
    """The six bank cuts of the census (build_visits.py:204-210), as ISO strings keyed by name."""
    y0 = test_years[0]
    first_test, first_inner = dt.date(y0, 1, 1), dt.date(y0 - INNER_SCORE_YEARS, 1, 1)
    out = {"L0_fit": (0, dt.date(y0 - 1, 12, 31)), "L0_inner": (0, dt.date(y0 - 1 - INNER_SCORE_YEARS, 12, 31))}
    for L in LEADS[1:]:
        out["L%d_fit" % L] = (L, first_test - dt.timedelta(days=L))
        out["L%d_guard" % L] = (L, first_inner - dt.timedelta(days=L))
    return {k: (L, c.isoformat()) for k, (L, c) in out.items()}


def compute(v):
    """Per-group facts and the V5/V6 lists from the visit table."""
    v = v.copy()
    v["target_date"] = pd.to_datetime(v.target_date).dt.strftime("%Y-%m-%d")   # ISO text compares as dates
    test = v[v.mark == "test"]
    if test.empty:
        raise SystemExit("refused: the visit table has no test row")
    years = pd.to_datetime(test.target_date).dt.year
    test_years = (int(years.min()), int(years.max()))
    cuts = cuts_of(test_years)
    sample = v[v.present_L0 & (v.mark != "unused")]
    y0 = test_years[0]
    tab = {}
    for g, m in sample.groupby("group", sort=True):
        tr = m.mark == "train"
        yr = pd.to_datetime(m.target_date).dt.year
        row = {"train": int(tr.sum()), "test": int((m.mark == "test").sum()), "units": int(m.unit_id.nunique()),
               "decision_rows": int((tr & yr.between(y0 - INNER_SCORE_YEARS, y0 - 1)).sum())}
        row["test_by_lead"] = {L: int(((m.mark == "test") & m["present_L%d" % L]).sum()) for L in LEADS}
        row["cut_rows"] = {name: int(((m.target_date <= c) & m["present_L%d" % L] & tr).sum())
                           for name, (L, c) in cuts.items()}
        row["sites_train"] = int(m[tr].unit_id.nunique())
        tab[g] = row
    v5, v6 = {}, {}
    for g, r in tab.items():
        zero = [k for k, n in r["cut_rows"].items() if n == 0]
        if zero or r["units"] == 1:
            v5[g] = (zero, r["units"] == 1)
    for g, r in tab.items():
        if g not in v5 and min(r["test_by_lead"].values()) == 0:
            v6[g] = r
    kept = [g for g in tab if g not in v5 and g not in v6]
    return test_years, cuts, tab, v5, v6, kept


def reason_v5(g, r, zero, one_site):
    parts = []
    if zero:
        if len(zero) == 6:
            parts.append("0 train rows at every bank cut (test rows: %d)" % r["test"])
        else:
            parts.append("0 train rows at the cuts %s (train rows: %d; test rows: %d)"
                         % (", ".join(zero), r["train"], r["test"]))
        parts.append("the table option refuses a group with 0 rows at any of the 6 bank cuts "
                     "(SPEC_TABLE_MODE.md 7 O13; fit/bank.py:200-206)")
    if one_site:
        parts.append("one site (%d train, %d test visits); derive_overlap_blocks refuses a one-unit group without "
                     "grid indices (split.py:795-797; SPEC_TABLE_MODE.md 7 O14)" % (r["train"], r["test"]))
    return "excluded by owner ruling V5 (%s): %s" % (SIGNED, "; ".join(parts))


def reason_v6(g, r, test_years):
    y0 = int(test_years[0])
    return ("excluded by owner ruling V6 (%s): no test row in the lead files after V5 (train visits: %s, sites: %s, "
            "%d-%d decision-surface rows: %s); under leave one region out a group with no test row cannot be "
            "scored (G-SPLIT; BUILD_NOTES_table.md:68-79); its rows also leave the neighbour pools and banks "
            "(package/table.py:505-507)" % (SIGNED, f"{r['train']:,}", f"{r['sites_train']:,}",
                                            y0 - INNER_SCORE_YEARS, y0 - 1, f"{r['decision_rows']:,}"))


def summary(test_years, tab, v5, v6, kept):
    s = lambda gs, k: int(sum(tab[g][k] for g in gs))   # noqa: E731
    return {"test_years": list(test_years), "groups": len(tab), "v5": len(v5), "v6": len(v6), "kept": len(kept),
            "v5_test": s(v5, "test"), "v5_train": s(v5, "train"), "v6_train": s(v6, "train"),
            "v6_test": s(v6, "test"), "v6_sites": s(v6, "sites_train"), "v6_decision": s(v6, "decision_rows"),
            "kept_train": s(kept, "train"), "kept_test": s(kept, "test"), "kept_decision": s(kept, "decision_rows"),
            "kept_decision_groups": int(sum(1 for g in kept if tab[g]["decision_rows"] > 0))}


def visits_from_lead_files(folder):
    """The visit frame rebuilt from a built folder's lead files (keys and mark only)."""
    import pyarrow.parquet as pq
    cols = ["row_id", "unit_id", "group", "target_date", "mark"]
    v = pq.read_table(os.path.join(folder, "lead_0.parquet"), columns=cols).to_pandas()
    v["target_date"] = pd.to_datetime(v.target_date).dt.strftime("%Y-%m-%d")
    v["present_L0"] = True
    for L in LEADS[1:]:
        ids = set(pq.read_table(os.path.join(folder, "lead_%d.parquet" % L), columns=["row_id"]).column(0).to_pylist())
        v["present_L%d" % L] = v.row_id.isin(ids).values
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--visits", default=os.path.join(BUILD_ROOT, "coral_data", "visits.parquet"))
    ap.add_argument("--lead-dir", default=None, help="a built folder (lead_<L>.parquet) instead of --visits")
    ap.add_argument("--split", default=DRAFT_SPLIT)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    A = ap.parse_args()
    for p in (A.split,):
        if not os.path.abspath(p).lower().startswith(BUILD_ROOT.lower()):
            raise SystemExit("refused: %s is not under %s" % (p, BUILD_ROOT))
    if A.lead_dir:
        v = visits_from_lead_files(A.lead_dir)
        A.visits = A.lead_dir
    else:
        v = pd.read_parquet(A.visits)
    test_years, cuts, tab, v5, v6, kept = compute(v)
    S = summary(test_years, tab, v5, v6, kept)
    print("test years %d-%d | cuts %s" % (test_years[0], test_years[1], cuts))
    print("V5 (%d): %s" % (len(v5), sorted(v5)))
    print("V6 (%d): %s" % (len(v6), sorted(v6)))
    print("counts: %s" % S)
    excluded = {}
    for g in sorted(v5):
        excluded[g] = reason_v5(g, tab[g], *v5[g])
    for g in sorted(v6):
        excluded[g] = reason_v6(g, tab[g], test_years)
    if A.write:
        if os.path.exists(A.split):
            dest = os.path.join(BUILD_ROOT, "_moved", "v_split_" + time.strftime("%Y%m%d_%H%M%S"))
            os.makedirs(dest, exist_ok=True)
            shutil.move(A.split, os.path.join(dest, "split.yaml"))
            print("old split.yaml moved to %s" % dest)
        y0 = int(test_years[0])
        head = HEADER % {"stamp": time.strftime("%Y-%m-%d"), "src": A.visits.replace("\\", "/"),
                         "pkg": os.path.basename(os.path.dirname(os.path.abspath(A.split))),
                         "ty0": y0, "ty1": int(test_years[1]), "dy0": y0 - INNER_SCORE_YEARS, "dy1": y0 - 1,
                         "n5": S["v5"], "t5": f"{S['v5_test']:,}", "r5": f"{S['v5_train']:,}", "n6": S["v6"],
                         "r6": f"{S['v6_train']:,}", "s6": f"{S['v6_sites']:,}", "d6": f"{S['v6_decision']:,}",
                         "nk": S["kept"], "rk": f"{S['kept_train']:,}", "tk": f"{S['kept_test']:,}",
                         "dk": f"{S['kept_decision']:,}"}
        with open(A.split, "w", encoding="utf-8", newline="\n") as f:
            f.write(head)
            f.write(yaml.safe_dump({"excluded": excluded, "seen_during_design": sorted(kept)}, sort_keys=False,
                                   width=4096, allow_unicode=False))
        print("wrote %s" % A.split)
        return 0
    have = yaml.safe_load(open(A.split, encoding="utf-8"))
    bad = []
    if set(have.get("excluded") or {}) != set(excluded):
        bad.append("excluded differs: only in file %s; only recomputed %s"
                   % (sorted(set(have.get("excluded") or {}) - set(excluded)),
                      sorted(set(excluded) - set(have.get("excluded") or {}))))
    if set(have.get("seen_during_design") or []) != set(kept):
        bad.append("seen_during_design differs: only in file %s; only recomputed %s"
                   % (sorted(set(have.get("seen_during_design") or []) - set(kept)),
                      sorted(set(kept) - set(have.get("seen_during_design") or []))))
    if bad:
        print("CHECK FAIL: " + " | ".join(bad))
        return 1
    print("CHECK PASS: %s matches the V5/V6 rules on %s" % (A.split, A.visits))
    return 0


if __name__ == "__main__":
    sys.exit(main())
