def _function_node(text, name):
    import ast
    (node,) = [n for n in ast.parse(text).body if isinstance(n, ast.FunctionDef) and n.name == name]
    return node


def test_the_builders_content_digest_keeps_the_running_builds_files_and_moves_with_content(tmp_path):
    """The owner's first full build ran the 2026-09-29 13:10 version; the resume and catalog checks added
    since change no statement that decides what a file holds, so that version is pinned as output-identical.
    The digest ignores the docstring, comments and the NOT_FILE_CONTENT functions, and moves with anything else."""
    import ast
    B = _builder()
    path = DEFO / "features" / "build_store.py"
    text = path.read_text(encoding="utf-8")
    today = B.content_sha256()
    assert B.OUTPUT_IDENTICAL_PREDECESSORS[RUNNING_BUILD_CODE_SHA256] == today
    assert B.sha256_file(str(path)) not in B.OUTPUT_IDENTICAL_PREDECESSORS      # only earlier versions are listed
    # every NOT_FILE_CONTENT name is a function of the file (a misspelt name would silently cover nothing)
    names = {n.name for n in ast.parse(text).body if isinstance(n, ast.FunctionDef)}
    assert set(B.NOT_FILE_CONTENT) <= names
    # build() writes the files and is outside the digest: its one write call is pinned here
    build_src = ast.get_source_segment(text, _function_node(text, "build"))
    assert build_src.count("pq.write_table(") == 1 and WRITE_CALL in build_src

    def digest(new_text, name):
        p = tmp_path / name
        p.write_text(new_text, encoding="utf-8")
        return B.content_sha256(str(p))

    first_doc_line = text.split("\n", 1)[0]
    cosmetic = text.replace(first_doc_line, first_doc_line + " (edited)", 1).replace(
        "def h_block(target, group):", "# a comment\ndef h_block(target, group):", 1)
    rs = _function_node(text, "resume_check")
    lines = text.split("\n")
    lines.insert(rs.body[-1].lineno - 1, "    assert True")                   # a statement inside resume_check
    assert digest(cosmetic, "cosmetic.py") == today
    assert digest("\n".join(lines), "resume_only.py") == today
    for old, new in (("YRS_SINCE_NONE = 99", "YRS_SINCE_NONE = 98"),
                     ("ncum[:, 1:] = np.cumsum(nbr0[:, :-1], axis=1)", "ncum[:, 1:] = np.cumsum(nbr0[:, 1:], axis=1)"),
                     ('COMPRESSION = "zstd"', 'COMPRESSION = "snappy"'),
                     ('rows, f = aggregate_time(frame[[p]], codes, steps, p, parent_view(pkg, p), YEAR, s, None)',
                      'rows, f = aggregate_time(frame[[p]], codes, steps, p, parent_view(pkg, p), YEAR, "mean", None)')):
        assert text.count(old) == 1, old
        assert digest(text.replace(old, new), "content.py") != today, old


