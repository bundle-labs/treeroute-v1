def test_the_h_block_uses_only_earlier_years_on_a_synthetic_grid():
    B = _builder()
    cells = ["g_%d_%d" % (i, j) for i in range(3) for j in range(3)]
    years = list(range(2001, 2008))
    rs = np.random.RandomState(0)
    rows = [(c, y, float(rs.rand() < 0.4) * rs.rand()) for c in cells for y in years]
    target = pd.DataFrame(rows, columns=["cell_id", "year", "loss_frac"])
    target.loc[target.cell_id == "g_0_0", "loss_frac"] = np.nan        # a cell without year-2000 forest
    c0, y0, h0 = B.h_block(target, "g")
    forested = target.cell_id != "g_0_0"
    rest = [i for i in range(9) if c0[i] != "g_0_0"]
    # changing the target at year t never moves a value at years <= t
    for t in years:
        changed = target.copy()
        changed.loc[forested & (changed.year >= t), "loss_frac"] = 0.9
        _, _, h1 = B.h_block(changed, "g")
        j = years.index(t)
        for k in H_KEPT:
            assert np.array_equal(h0[k][:, :j + 1], h1[k][:, :j + 1], equal_nan=True), (k, t)
    # the shipped form cumsum(nbr) - nbr is NOT built from earlier years alone: its rounding moves with year t
    def shipped_cum(frame):
        _, _, hh = B.h_block(frame, "g")
        nbr = np.nan_to_num(np.column_stack([hh["h_nbr1"][:, 1:], np.full((9, 1), np.nan)]))[rest]
        return np.cumsum(nbr, axis=1) - nbr
    moved = False
    for t in years[1:-1]:
        changed = target.copy()
        changed.loc[forested & (changed.year >= t), "loss_frac"] = 0.9
        j = years.index(t)
        moved |= not np.array_equal(shipped_cum(target)[:, j], shipped_cum(changed)[:, j])
    assert moved
    # the centre cell's neighbour mean at t-1 is the mean of the 7 forested others (the cell without forest is
    # not a neighbour, as in the shipped pivot, and gets NaN everywhere)
    centre = list(c0).index("g_1_1")
    nof = list(c0).index("g_0_0")
    A = target.pivot(index="cell_id", columns="year", values="loss_frac").reindex(c0).fillna(0.0).to_numpy()
    others = [i for i in range(9) if i not in (centre, nof)]
    assert h0["h_nbr1"][centre, 3] == pytest.approx(A[others, 2].mean())
    for k in H_KEPT:
        assert np.isnan(h0[k][nof]).all(), k
    assert np.isnan(h0["h_nbr1"][:, 0]).all() and np.isnan(h0["h_nbr2"][:, :2]).all()
    assert (h0["h_nbr_cum"][rest, 0] == 0).all()
    mixed = target.copy()
    mixed.loc[(mixed.cell_id == "g_1_1") & (mixed.year == 2004), "loss_frac"] = np.nan
    with pytest.raises(B.BuildError):
        B.h_block(mixed, "g")
    hot = A > 0
    for i in rest:
        for j, y in enumerate(years):
            prev = [years[k] for k in range(j) if hot[i, k]]
            assert h0["h_yrs_since"][i, j] == (y - prev[-1] if prev else 99)


