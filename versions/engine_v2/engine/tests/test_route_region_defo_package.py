def _monthly_parents(pkg):
    """The one-month panel columns whose aggregates the catalog declares (role engineered), in the order of
    their first aggregate: the parents themselves are not catalog rows (owner ruling J4; defo_draft never
    listed them)."""
    panel = pkg.stores[PANEL_CATALOG]
    out = []
    for c, f in pkg.catalog.columns.items():
        head, _, stat = c.rpartition("_")
        if f.role == "engineered" and stat in STATS and head not in out and head in panel.columns:
            cad = panel.columns[head].cadence
            if (cad.kind, cad.length, cad.unit) == ("regular", 1, "month"):
                out.append(head)
    return out


