def _lag(pkg, column, store_facts, co_measured=None):
    from treeroute.timing import compute_lag
    view = NS(name=column, cadence=store_facts.cadence, stamp=store_facts.stamp, window=store_facts.window,
              fact_status=store_facts.fact_status, co_measured_with_target=co_measured)
    return compute_lag(view, _target_view(pkg), YEAR, "nowcast").steps


