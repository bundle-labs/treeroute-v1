    assert info.value.rule == "G-CLOSED" and "target_twin" in str(info.value)
    text = (FIRE_DIR / "catalog.yaml").read_text(encoding="utf-8")
    assert "OWNER RULING NEEDED BEFORE Q34" not in text and "RULED (J1, 2026-10-05" in text


