def _random_grid(seed_text="fire", nla=9, nlo=11, nmon=72, p_burn=0.08, p_unobs=0.03):
    """A deterministic synthetic burned-fraction grid (the draw is fixed by the text, not a seed knob)."""
    rs = np.random.RandomState(sum(ord(c) for c in seed_text))
    burn = rs.uniform(size=(nla, nlo, nmon)) < p_burn
    grid = np.where(burn, rs.uniform(0.01, 1.0, size=(nla, nlo, nmon)), 0.0).astype(np.float32)
    grid[rs.uniform(size=grid.shape) < p_unobs] = np.nan
    lat_axis = 10.0 + 0.03593 * np.arange(nla)
    return grid, lat_axis


