def test_the_target_reader_census_validity_and_key_map(toy):
    load_module(toy.pkg / "ingest" / "build_static.py", "fire_bs_toy3").build(toy.pkg)
    tr = load_module(toy.pkg / "ingest" / "target_reader.py", "fire_tr_toy")
