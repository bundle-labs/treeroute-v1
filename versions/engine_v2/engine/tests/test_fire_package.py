def test_the_firecci_burned_area_columns_are_target_twins_in_the_fire_package():
    """The three FireCCI columns measure the same fire events as the target (sheet: co-measured candidate; the
    shipped run banned them as the label). RULED (J1, 2026-10-05: the Q34 review's section 5 C adopted): in the fire
    package they are target_twin, which forces their ban (io.apply_verdicts refuses any other verdict) and refuses
    a feature derived from them; ban.yaml bans them as 'label'. fire_draft (the installed package since 2026-10-06)
    reads the same."""
    from treeroute.errors import RefusedError
    from treeroute.io.apply import apply_verdicts
    from treeroute.package.load import load_package

    draft, fire = load_package(DRAFT_DIR), load_package(FIRE_DIR)
    sheet = pd.read_csv(SHEET).set_index("column")
    for c in FIRECCI_BURNED_AREA:
        assert draft.ban.verdicts[c].verdict == "ban" and draft.ban.verdicts[c].reason == "label", c
        assert sheet.loc[c, "current_verdict"] == "ban" and sheet.loc[c, "co_measured_candidate"].startswith("yes")
        assert draft.catalog.columns[c].role == "target_twin", c
        assert fire.catalog.columns[c].role == "target_twin", c
        assert (fire.ban.verdicts[c].verdict, fire.ban.verdicts[c].reason) == ("ban", "label"), c
    # the twin role forces the ban: a 'keep' is refused
    cols = tuple(c for c, f in fire.catalog.columns.items() if f.role not in KEY_ROLES)
    roles = {c: fire.catalog.columns[c].role for c in cols}
    verdicts = dict(fire.ban.verdicts)
    verdicts["V20_burned_binary"] = fire.ban.verdicts["V25_elevation_m"]
