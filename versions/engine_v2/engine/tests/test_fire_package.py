    hits = g_hist_matches(flat, y)
    assert sorted(hits) == sorted(G_HIST_SPARSE_LAG), hits
    assert "y(t-%d) (informative rows)" % lag in hits["last_burn_size"]
    assert not any("every row" in h for h in hits["last_burn_size"])
