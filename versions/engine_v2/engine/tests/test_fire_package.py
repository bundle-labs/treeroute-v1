def _write(path, frame):
    path.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(pa.Table.from_pandas(frame, preserve_index=False), str(path))


def _toy_package(tmp_path, units, years=(2003, 2004)):
    """A package folder holding copies of the fire ingest code and a dataset.yaml whose stores live in tmp."""
    pkg = tmp_path / "pkg"
    (pkg / "ingest").mkdir(parents=True)
    (pkg / "features").mkdir(parents=True)
    for rel in ("ingest/target_reader.py", "ingest/build_static.py", "ingest/build_sidecars.py",
                "ingest/build_history.py", "features/target_history.py"):
        (pkg / rel).write_bytes((FIRE_DIR / rel).read_bytes())
    store = tmp_path / "stores"
    ds = {"stores": {"target": (store / "target" / "{group}_{year}.parquet").as_posix(),
                     "static": "data/static/part-0.parquet",
                     "drivers": [(store / "panel" / "{group}_monthly_{year}.parquet").as_posix()]}}
    (pkg / "dataset.yaml").write_text(yaml.safe_dump(ds), encoding="utf-8")
    return pkg, store


def _grid_cells(group, n_lat=3, n_lon=4, lat0=10.0, lon0=20.0, step=0.03593):
    cells = []
    for a in range(n_lat):
        for b in range(n_lon):
            lat = np.float32(lat0 + a * step)
            lon = np.float32(lon0 + b * step)
            cells.append(("%s_%d_%d" % (group, 100 + b, 200 + a), lat, lon))
    return cells


def _panel_file(store, group, year, cells):
    rows = [(cid, lat, lon, year, m) for cid, lat, lon in cells for m in range(1, 13)]
    frame = pd.DataFrame(rows, columns=["cell_id", "lat", "lon", "year", "month"])
    frame["lat"] = frame["lat"].astype(np.float32)
    frame["lon"] = frame["lon"].astype(np.float32)
    _write(store / "panel" / ("%s_monthly_%d.parquet" % (group, year)), frame)


def _target_file(store, group, year, cells, y=None, n_valid=None, drop=()):
    rows = []
    for k, (_, lat, lon) in enumerate(cells):
        for m in range(1, 13):
            if (k, m) in drop:
                continue
            bf = 0.0 if y is None else y.get((k, m), 0.0)
            nv = 50 if n_valid is None else n_valid.get((k, m), 50)
            rows.append((lat, lon, year, m, int(round(bf * nv)), nv, 0, bf if nv > 0 else np.nan, 0.0))
    frame = pd.DataFrame(rows, columns=["lat", "lon", "year", "month", "n_burned", "n_valid", "n_unmapped",
                                        "burned_frac", "unmapped_frac"])
    frame["lat"] = frame["lat"].astype(np.float32)
    frame["lon"] = frame["lon"].astype(np.float32)
    frame["n_burned"] = frame["n_burned"].astype(np.int32)
    frame["n_valid"] = frame["n_valid"].astype(np.int32)
    frame["n_unmapped"] = frame["n_unmapped"].astype(np.int32)
    _write(store / "target" / ("%s_%d.parquet" % (group, year)), frame)


