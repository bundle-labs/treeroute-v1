def _engine_history_reference(y, start_offset):
    """The engine's own-history block for a unit x month label grid (R17: the last 3 values and the 12-month,
    60-month and all-history means), newest label t-1-start_offset; NaN where not defined."""
    nu, nm = y.shape
    out = {}
    newest = 1 + start_offset
    for k in range(1, 4):
        v = np.full((nu, nm), np.nan)
        lag = newest + k - 1
        v[:, lag:] = y[:, :-lag]
        out["hist_last_%d" % k] = v
    for w in (12, 60, None):
        v = np.full((nu, nm), np.nan)
        for t in range(newest, nm):
            lo = 0 if w is None else max(0, t - newest - w + 1)
            window = y[:, lo:t - newest + 1]
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", RuntimeWarning)      # a unit with no finite label yet: NaN
                v[:, t] = np.nanmean(window, axis=1) if window.shape[1] else np.nan
        out["hist_mean_%s" % ("all" if w is None else w)] = v
    return out


G_HIST_MAX_LAG = 12          # plain lags y(t-1) ... y(t-12) are compared
G_HIST_MIN_ROWS = 50         # a comparison needs this many rows
G_HIST_SHARE = 0.99          # equal on this share of the informative rows counts as a duplicate


def g_hist_matches(cols, y):
    """{column: [what it duplicates]} for the G-HIST sample match (plan 5: 'refused by declaration and by a sample
    match'). cols: {column: units x months}; y: the labels, units x months (NaN = unobserved). The references are
    the engine's own-history block (R17) starting at t-1 (@0) and at t-2 (@1, fire under ruling R-D b) and the
    plain lags y(t-1) ... y(t-12). A column duplicates a reference when it equals it (atol 1e-6) on every row
    where both are defined, OR on at least G_HIST_SHARE of the rows where the reference is informative (defined
    and non-zero): a sparse copy that differs only where the reference is 0 (y(t-k) = 0, no burn) is still a
    copy of the unit's own y."""
    refs = {}
    for offset in (0, 1):
        for name, v in _engine_history_reference(y, offset).items():
            refs["%s@%d" % (name, offset)] = v
    for k in range(1, G_HIST_MAX_LAG + 1):
        v = np.full(y.shape, np.nan)
        v[:, k:] = y[:, :-k]
        refs["y(t-%d)" % k] = v
    out = {}
    for c, values in cols.items():
        v = np.asarray(values, dtype=np.float64)
        hits = []
        for r, ref in refs.items():
            both = np.isfinite(v) & np.isfinite(ref)
            informative = both & (ref != 0)
            if both.sum() >= G_HIST_MIN_ROWS and np.allclose(v[both], ref[both], atol=1e-6):
                hits.append("%s (every row)" % r)
            elif informative.sum() >= G_HIST_MIN_ROWS and \
                    np.mean(np.isclose(v[informative], ref[informative], atol=1e-6)) >= G_HIST_SHARE:
                hits.append("%s (informative rows)" % r)
        if hits:
            out[c] = hits
    return out


@pytest.mark.parametrize("lag", [1, 2])
def test_g_hist_no_column_duplicates_the_engine_history_block_or_a_plain_lag(th, lag):
    """No column equals the engine's own-history block or a plain lag on every row; ONE column, last_burn_size,
    equals y(t-lag) wherever that lag is non-zero (a sparse own lag): exactly G_HIST_SPARSE_LAG, which the
    draft bans. The planted copies prove the sample match fires."""
    grid, la = _random_grid("ghist", nla=8, nlo=8, nmon=96, p_burn=0.15)
