def own_weight_at_edges(th, r):
    """(corner, edge, one cell in): the weight of a unit's OWN value in its ring mean of radius r cells."""
    n = 2 * r + 4
    out = []
    for i, j in ((0, 0), (0, n // 2), (1, n // 2)):
        a = np.zeros((n, n, 1), np.float32)
        a[i, j, 0] = 1.0
        out.append(float(th._ring_mean(a, r)[i, j, 0]))
    return tuple(out)


@pytest.mark.parametrize("r", [6, 17, 19, 52])        # the radii range over the 40 region grids (25 km / 75 km)
def test_ring_edge_padding_puts_the_units_own_value_in_its_ring(th, r):
    """DISCLOSED (catalog.yaml RING EDGES; fire_draft AUDIT_CHECKLIST): the shipped ring mean pads the region grid with
    scipy's 'nearest' mode, so on the grid's outermost row or column the unit's own cell is repeated inside its own
    ring: weight (r+2)/(4(r+1)) at a corner, r/((2r+1)^2-1) on an edge, and 0 one cell in. The exact-equality
    G-HIST check above cannot see this partial own-history signal; the owner rules it in Q34."""
    corner, edge, inner = own_weight_at_edges(th, r)
    assert corner == pytest.approx((r + 2) / (4.0 * (r + 1)), abs=1e-6)
    assert edge == pytest.approx(r / ((2.0 * r + 1) ** 2 - 1), abs=1e-6)
    assert inner == pytest.approx(0.0, abs=1e-6)
    assert 0.25 < corner <= 0.2858 and 0.004 < edge <= 0.0358            # the disclosed ranges


