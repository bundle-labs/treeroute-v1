    out = tr.read_target_file(f03, {"group": "grp_a", "year": 2003})
    assert list(out.columns) == list(tr.COLUMNS)
    assert len(out) == 11 * 12                                   # every unit x every month
    assert out.groupby("cell_id").size().eq(12).all()
    assert set(out.region) == {"grp_a"} and set(out.year) == {2003}
    cid = {k: c for k, (c, _, _) in enumerate(toy.cells_a)}
    y = out.set_index(["cell_id", "month"]).burned_frac
    assert y[(cid[0], 3)] == 0.25
    assert np.isnan(y[(cid[1], 5)])                              # n_valid 0 -> NaN
    assert np.isnan(y[(cid[2], 6)])                              # no row -> NaN (complete census)
    assert int(out.burned_frac.isna().sum()) == 2
