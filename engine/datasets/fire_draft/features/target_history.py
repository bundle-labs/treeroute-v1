"""Fire package: the fire-history columns recomputed from the TARGET, strictly before each row (plan 1.5
'target-derived columns use y strictly BEFORE their own row'; plan 3.2 fire: 'tslf / n_burns / burn_rate /
last_burn / nbr checked against G-HIST').

WHAT THIS IS. The 19 columns of the shipped fire-history store (D:/fire/history, fire_build_history.py) are
target-derived. catalog.yaml declares them with role engineered; their facts (derived_from burned_frac, the
operation, reads_target true, the window) are the store catalog's (the shipped store's:
engine/datasets/_stores/fire_history_schema_catalog.yaml; the rebuilt store's: ingest/fire_history_store_catalog.yaml,
generated by ingest/build_history.py). This module is their RECOMPUTE from the target:
  - the reference a G-DERIVED check compares the stored values against (plan 5: 'every engineered column
    recomputed on a stride sample'); tests/test_fire_package_data.py compares it at label lag 1 with
    D:/fire/history on the cells that store covers, value for value, and at label lag 2 with fire_draft's
    rebuilt store;
  - the builder of the package's store at the ruled label lag (below), for every unit or a unit list
    (ingest/build_history.py; the shipped store holds the 1,000-cell pick per group only).
It is not an output of features/build.py: the engine's feature hook refuses outputs declared reads_target
and hands the script no labels (engine item; see features/build.py).

THE LABEL LAG (RULED, OWNER_RULINGS_2026-09-28.md B R-D (b)). Month m's MCD64A1 label uses observations from
month m+1 (the detection window; catalog.yaml burned_frac: reach_after_max 1 month), so the engine's own history
block starts at t-2 (R17 start_offset_steps 1 = timing.target_reach_offset_steps of the target's window fact).
A target-derived column may read no later label than R17 does: NEWEST_LABEL_LAG = 1 + that offset = 2, so every
column at month t reads labels of months <= t-2 only. tests/test_fire_package.py pins NEWEST_LABEL_LAG to
1 + timing.target_reach_offset_steps(the package's target facts). The shipped store D:/fire/history was built at
lag 1 (Part 492: every window ends at t-1), which under R-D (b) reads a label whose observations reach into the
row's own month (the month-boundary bleed fire_architecture.py:128-139 banned the single-month rings for). It is
reproduced exactly with newest_label_lag=SHIPPED_NEWEST_LABEL_LAG (tests/test_fire_package_data.py: the check of
this code against the shipped store) and is NOT the package's store: ingest/build_history.py writes the columns
at NEWEST_LABEL_LAG.

THE COLUMNS (fire_build_history.py:92-190, reproduced exactly at newest label lag 1). With L the newest label
lag, every column at month t reads labels of months <= t - L only:
  fuel age      tslf_months      months since the last burn at or before t-L, capped at CAP (300); CAP if none
                                 (so its smallest value is L)
                tslf_censored    1 where tslf_months is at the cap
                last_burn_month  calendar month (1..12) of that burn; -1 if none
                last_burn_size   the cell's burned fraction at that burn; 0 if none
  frequency     n_burns_12mo, n_burns_60mo   burned months (burned fraction > 0) in the 12 / 60 months ending
                                             at t-L (fewer at the start of the record)
                burn_rate_120mo  burned months / observed months (at least 1) in the 120 months ending at t-L
  neighbours    nbr{25,75}km_lag{k}       ring mean of the burned fraction k months before t
                nbr{25,75}km_12mo_lag{k}  ring mean of 'burned at all in the 12 months ending at t-k'
                The shipped ring lags are k = 1, 3, 6 (SHIPPED_RING_LAGS). A ring lag below L is refused, so at
                L = 2 the four lag-1 rings (REFUSED_COLUMNS) are not built and the package's store holds 15
                columns (COLUMNS), not the shipped 19 (SHIPPED_COLUMNS).
                The ring is a TRUE ring: the box of radius round(km / cell height) cells around the cell, on the
                target product's full lat/lon grid, with the cell itself removed; every target cell counts as a
                neighbour, unit or not (fire_build_history.py:30-35).
  A burned fraction is 'burned' when > 0; an unobserved month (n_valid = 0, or a cell-month absent from the
  store) is NaN in the grid and counts as 0 (not burned) for every column except the observed-month count of
  burn_rate_120mo, exactly as shipped.

G-HIST (plan 5; 1.5 'Forbidden: lags, trailing or cumulative sums and means of the unit's own y'; 'Allowed:
event counts, years since the last event and neighbour aggregates'). tests/test_fire_package*.py check on real
and synthetic grids that no column equals a column of the engine's own-history block (R17: the last 3 values and
the 12-month, 60-month and all-history means, from t-2) or a plain lag y(t-k), neither on every row nor on the
rows where that lag or mean is informative (non-zero). ONE COLUMN FAILS the second check at every L:
last_burn_size is y(t - tslf_months), so it equals y(t-L) on every row where y(t-L) > 0 (a sparse own lag).
It is still BUILT here (a store column; the recompute reproduces the store); the verdict is the owner's (Q34
G-HIST review, plan 3.2). fire_draft bans it by rule (tests/test_fire_package.py, G_HIST_REASON).

Pure numpy / scipy: no file is read, no model is fitted, no random number is drawn.
"""
# Provenance: fire_build_history.py:38-59 (constants), :64-190 (the computation), :230-236 (the leak assertion);
# engine/datasets/_stores/fire_history_schema_catalog.yaml (the columns' facts); APP_PLAN.md 1.5, 3.2, 5 G-HIST;
# OWNER_RULINGS_2026-09-28.md B R-D (b).

import numpy as np
from scipy.ndimage import uniform_filter

CAP = 300.0                 # months (fire_build_history.py:54)
RINGS_KM = (25.0, 75.0)     # fire_build_history.py:57
SHIPPED_RING_LAGS = (1, 3, 6)   # fire_build_history.py:58
KM_PER_DEG_LAT = 111.32     # fire_build_history.py:160
MONTHS_PER_YEAR = 12
SHIPPED_NEWEST_LABEL_LAG = 1    # D:/fire/history (Part 492: every window ends at t-1)
NEWEST_LABEL_LAG = 2        # RULED R-D (b): 1 + R17's start offset (module docstring, THE LABEL LAG)

FUEL_COLUMNS = ("tslf_months", "tslf_censored", "last_burn_month", "last_burn_size",
                "n_burns_12mo", "n_burns_60mo", "burn_rate_120mo")


def ring_columns(ring_lags=SHIPPED_RING_LAGS, rings_km=RINGS_KM):
    """The neighbour column names in the store's order (lag outer, ring inner, single month then 12 months)."""
    out = []
    for lag in ring_lags:
        for km in rings_km:
            out.append("nbr%dkm_lag%d" % (int(km), lag))
            out.append("nbr%dkm_12mo_lag%d" % (int(km), lag))
    return tuple(out)


def allowed_ring_lags(newest_label_lag, ring_lags=SHIPPED_RING_LAGS):
    """The ring lags a newest label lag allows (ring lag k reads the label of month t-k)."""
    return tuple(k for k in ring_lags if k >= int(newest_label_lag))


RING_LAGS = allowed_ring_lags(NEWEST_LABEL_LAG)                          # (3, 6)
SHIPPED_COLUMNS = FUEL_COLUMNS + ring_columns(SHIPPED_RING_LAGS)          # the 19 of D:/fire/history
COLUMNS = FUEL_COLUMNS + ring_columns(RING_LAGS)                          # the 15 of the package's store
REFUSED_COLUMNS = tuple(c for c in SHIPPED_COLUMNS if c not in COLUMNS)   # the four lag-1 rings


class HistoryRefusal(Exception):
    """A request this recompute cannot serve (fail loudly)."""


def _shift(a, k):
    """a moved k months later along the last axis (month t holds month t-k); the first k months are 0/False."""
    out = np.zeros_like(a)
    if 0 < k < a.shape[2]:
        out[:, :, k:] = a[:, :, :-k]
    elif k == 0:
        out[...] = a
    return out


def _trail(a, w):
    """Trailing sum over w months ending at each month (fewer at the start), in float32 cumulative sums as
    shipped (fire_build_history.py:134-139)."""
    c = np.cumsum(a.astype(np.float32), axis=2)
    out = np.empty_like(c)
    out[:, :, :w] = c[:, :, :w]
    out[:, :, w:] = c[:, :, w:] - c[:, :, :-w]
    return out


def _ring_mean(a, rad):
    """Box mean with the centre cell removed (fire_build_history.py:162-166; scipy's 'nearest' edge mode)."""
    n = float((2 * rad + 1) ** 2)
    box = uniform_filter(a, size=(2 * rad + 1, 2 * rad + 1, 1), mode="nearest")
    return (box * n - a) / (n - 1.0)


def ring_radius_cells(lat_axis, km):
    """round(km / cell height) cells, at least 1; the cell height is the median lat spacing (4 km if one row)."""
    la = np.asarray(lat_axis, dtype=np.float64)
    dlat_km = float(np.median(np.diff(la))) * KM_PER_DEG_LAT if len(la) > 1 else 4.0
    return max(1, int(round(km / max(dlat_km, 1e-6))))


def grid_positions(la, lo, lat, lon):
    """(i, j) of each (lat, lon) on the grid axes (5-decimal rounding, the key); refuses a point that is not on
    them. The axes are the target product's region grid (ingest/build_history.py reads D:/fire/geom), not the
    distinct values of the target: a grid row the target never holds still pads the rings at the edge."""
    rlat = np.round(np.asarray(lat, dtype=np.float64), 5)
    rlon = np.round(np.asarray(lon, dtype=np.float64), 5)
    i = np.searchsorted(la, rlat)
    j = np.searchsorted(lo, rlon)
    ok = (i < len(la)) & (j < len(lo))
    ok[ok] = (la[i[ok]] == rlat[ok]) & (lo[j[ok]] == rlon[ok])
    if not ok.all():
        raise HistoryRefusal("%d points are not on the grid axes" % int((~ok).sum()))
    return i, j


def history_columns(burned_frac_grid, lat_axis, newest_label_lag=NEWEST_LABEL_LAG, ring_lags=None,
                    rings_km=RINGS_KM):
    """The columns on a whole region grid (15 at NEWEST_LABEL_LAG; the shipped 19 at lag 1).

    burned_frac_grid: float array [lat index, lon index, month], month 0 = January of the first year; NaN =
        unobserved (invalid label, or no row in the store). Values in [0, 1].
    lat_axis: the grid's latitude axis (for the ring radius in cells).
    newest_label_lag: L >= 1; month t reads labels of months <= t - L only.
    ring_lags: the ring lags to build; None = every shipped ring lag L allows (allowed_ring_lags).
    Returns {column: float32 array of the grid's shape}: the fuel columns, then the rings (ring_columns order).
    Refuses: L < 1 (a column would read its own row's label); a ring lag below L; a value outside [0, 1].
    """
    L = int(newest_label_lag)
    if ring_lags is None:
        ring_lags = allowed_ring_lags(L)
    if L < 1:
        raise HistoryRefusal("newest_label_lag %d < 1: a target-derived column reads only labels strictly before "
                             "its row (plan 1.5)" % L)
    low = [k for k in ring_lags if k < L]
    if low:
        raise HistoryRefusal("ring lags %s read labels after t-%d" % (low, L))
    B = np.asarray(burned_frac_grid, dtype=np.float32)
    if B.ndim != 3:
        raise HistoryRefusal("the burned-fraction grid must be [lat, lon, month], got shape %s" % (B.shape,))
    finite = B[np.isfinite(B)]
    if finite.size and (finite.min() < 0 or finite.max() > 1):
        raise HistoryRefusal("burned fractions outside [0, 1]")
    nla, nlo, nmon = B.shape
    obs = ~np.isnan(B)
    Bz = np.where(obs, B, 0.0).astype(np.float32)
    burned = (Bz > 0)

    # fuel age: the latest burn at or before t-L (the update comes BEFORE the write: strict inequality)
    tslf = np.full((nla, nlo, nmon), CAP, np.float32)
    last_mon = np.full((nla, nlo, nmon), -1.0, np.float32)
    last_size = np.zeros((nla, nlo, nmon), np.float32)
    cur = np.full((nla, nlo), -1, np.int32)
    cur_mon = np.full((nla, nlo), -1, np.int32)
    cur_size = np.zeros((nla, nlo), np.float32)
    for t in range(nmon):
        s = t - L
        if s >= 0:
            b = burned[:, :, s]
            cur = np.where(b, s, cur)
            cur_mon = np.where(b, (s % MONTHS_PER_YEAR) + 1, cur_mon)
            cur_size = np.where(b, Bz[:, :, s], cur_size)
        hit = cur >= 0
        tslf[:, :, t] = np.where(hit, np.minimum(t - cur, CAP), CAP)
        last_mon[:, :, t] = np.where(hit, cur_mon, -1)
        last_size[:, :, t] = np.where(hit, cur_size, 0.0)
    censored = (tslf >= CAP).astype(np.float32)

    # frequency: trailing windows on the burn matrix moved L months later
    past = _shift(burned, L)
    n12 = _trail(past, 12)
    n60 = _trail(past, 60)
    n120 = _trail(past, 120)
    seen120 = np.maximum(_trail(_shift(obs, L), 120), 1.0)
    rate120 = n120 / seen120

    out = {"tslf_months": tslf, "tslf_censored": censored, "last_burn_month": last_mon,
           "last_burn_size": last_size, "n_burns_12mo": n12, "n_burns_60mo": n60, "burn_rate_120mo": rate120}
    for lag in ring_lags:
        sh = _shift(Bz, lag)
        t12 = (_trail(_shift(burned, lag), 12) > 0).astype(np.float32)
        for km in rings_km:
            rad = ring_radius_cells(lat_axis, km)
            out["nbr%dkm_lag%d" % (int(km), lag)] = _ring_mean(sh, rad)
            out["nbr%dkm_12mo_lag%d" % (int(km), lag)] = _ring_mean(t12, rad)
    names = FUEL_COLUMNS + ring_columns(ring_lags, rings_km)
    # the leak assertion (fire_build_history.py:230-236): a cell burning at t never has tslf 0 at t
    if bool(((tslf == 0) & burned).any()):
        raise HistoryRefusal("LEAK: a cell-month burning at t has tslf 0 at t")
    return {c: np.asarray(out[c], dtype=np.float32) for c in names}


def month_index(years, months, first_year):
    """Grid month of (year, month): 0 = January of first_year."""
    return (np.asarray(years, dtype=np.int64) - int(first_year)) * MONTHS_PER_YEAR + np.asarray(months, dtype=np.int64) - 1


