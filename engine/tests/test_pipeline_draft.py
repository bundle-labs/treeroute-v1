"""The DRAFT development packages datasets/<name>_draft/ and the DRAFT stamp (tests may name problems).

UPDATED 2026-10-06 (agent C1). A draft is now the real package AS INSTALLED -- its owner-ruled ban list (owner ruling J,
OWNER_RULINGS_2026-10-05.md section J: the author's answer, not quoted, with rulings K and L) -- stamped DRAFT,
so a full-size rehearsal of a draft reads today's ban lists and nothing it produces can enter a headline table. The
one generator is datasets/_tools/refresh_drafts.py (draft_files): every file of the real package byte for byte
(expected_derived.json left out), dataset.yaml with the draft's name, version, owner and a stamped description, and
ban.yaml with the real verdicts and reasons and every evidence field stamped. This file checks all four drafts
against that generator, so a draft cannot drift from its package silently.

WHAT CHANGED. Until 2026-10-06 pm25_draft's ban.yaml was the SHIPPED verdicts of the Q34 review sheet
(review/v2/pm25_columns.csv) with a G-LAG departure for 12 index columns, generated by this file; ruling J replaced
those verdicts with the owner's, and ruling L1 (b) signed the 12 windows, so both the generator and its departure
are stale. The earlier drafts were moved aside, not deleted (datasets/_moved_20261006/<name>_draft/), and this file's
earlier text is kept in datasets/_moved_20261006/tests_before_draft_refresh/test_pipeline_draft.py.

The engine reads the stamp by its marker (treeroute.pipeline.draft.DRAFT_MARKER), never by a package name.
"""

import importlib.util
import re

import pytest
import yaml

from conftest import ENGINE_DIR

DATASETS = ENGINE_DIR / "datasets"
PACKAGES = ("pm25", "fire", "ndvi", "defo")
KEY_ROLES = ("key_unit", "key_group", "key_time")


def _tool():
    path = DATASETS / "_tools" / "refresh_drafts.py"
    spec = importlib.util.spec_from_file_location("refresh_drafts_under_test", str(path))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


R = _tool()
DRAFT_STAMP = R.DRAFT_STAMP


# ------------------------------------------------------------------------------------------------
@pytest.mark.parametrize("name", PACKAGES)
def test_the_draft_is_what_the_generator_writes_from_the_real_package(name):
    assert R.differences(name) == [], "run: py -3.9 datasets/_tools/refresh_drafts.py refresh %s" % name


@pytest.mark.parametrize("name", PACKAGES)
def test_the_draft_copies_are_byte_identical_to_the_package_code(name):
    real, draft = DATASETS / name, DATASETS / ("%s_draft" % name)
    copied = R.real_files(name)
    assert {"catalog.yaml", "split.yaml", "exceptions.yaml", "AUDIT_CHECKLIST.md", "features/build.py",
            "ingest/target_reader.py"} <= set(copied)
    for rel in copied:
        assert (draft / rel).read_bytes() == (real / rel).read_bytes(), rel
    assert not (draft / "expected_derived.json").exists()          # the real package's acceptance values only
    ds_draft = yaml.safe_load((draft / "dataset.yaml").read_text(encoding="utf-8"))
    ds_real = yaml.safe_load((real / "dataset.yaml").read_text(encoding="utf-8"))
    assert ds_draft["stores"] == ds_real["stores"] and ds_draft["includes"] == ds_real["includes"]
    assert set(ds_draft) == set(ds_real)
    for key in set(ds_real) - {"name", "version", "owner", "description"}:
        assert ds_draft[key] == ds_real[key], key
    assert ds_draft["name"] == name + "_draft" and ds_draft["version"] == ds_real["version"] + "-draft"
    assert ds_draft["description"] == "%s. %s" % (DRAFT_STAMP, ds_real["description"])


@pytest.mark.parametrize("name", PACKAGES)
def test_the_draft_loads_with_todays_ban_list_and_every_verdict_stamped(name):
    from treeroute.package.load import load_package

    pkg = load_package(DATASETS / ("%s_draft" % name))
    real = load_package(DATASETS / name)
    assert pkg.dataset.name == name + "_draft"
    assert DRAFT_STAMP in pkg.dataset.description
    non_key = [c for c, f in pkg.catalog.columns.items() if f.role not in KEY_ROLES]
    assert sorted(pkg.ban.verdicts) == sorted(non_key)            # closed world
    assert sorted(pkg.ban.verdicts) == sorted(real.ban.verdicts)
    for c, v in pkg.ban.verdicts.items():
        r = real.ban.verdicts[c]
        assert (v.verdict, v.reason) == (r.verdict, r.reason), c   # today's owner-ruled verdict, unchanged
        assert v.evidence.startswith(DRAFT_STAMP + " | "), c
        assert v.evidence[len(DRAFT_STAMP) + 3:] == (r.evidence or "(no evidence in the real ban list)"), c
    assert pkg.catalog == real.catalog and pkg.split == real.split and pkg.exceptions == real.exceptions
    assert pkg.fingerprint != real.fingerprint


@pytest.mark.parametrize("name", PACKAGES)
def test_the_engine_reads_the_draft_stamp(name):
    from treeroute.package.load import load_package
    from treeroute.pipeline.draft import draft_status

    pkg = load_package(DATASETS / ("%s_draft" % name))
    draft = draft_status(pkg)
    assert draft.is_draft and draft.stamped_verdicts == len(pkg.ban.verdicts) and draft.stamp == DRAFT_STAMP
    assert "dataset.yaml description" in draft.where
    real = draft_status(load_package(DATASETS / name))
    assert not real.is_draft and real.stamped_verdicts == 0


def test_the_draft_marker_is_not_a_package_name():
    """The engine detects the stamp by its marker text, never by the package name (G-NONAMES)."""
    from treeroute.pipeline import draft

    for name in PACKAGES:
        assert name not in draft.DRAFT_MARKER.lower()
    assert re.match(r"^DRAFT --", DRAFT_STAMP)
    assert DRAFT_STAMP.startswith(draft.DRAFT_MARKER)
    assert "|" not in DRAFT_STAMP and "." not in DRAFT_STAMP       # read whole from ban.yaml and dataset.yaml
